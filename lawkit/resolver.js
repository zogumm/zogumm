/**
 * 건폐율·용적률 판정 엔진.
 *
 * 연산은 셋뿐이다. 순서가 전부다.
 *
 *   gate     구역을 보고 트랙을 연다/닫는다   ← 특별법 구역이면 국토계획법 트랙 폐쇄
 *   override 값을 갈아끼운다                  ← 특별법 특례 (완화 방향)
 *   cap      상한을 씌운다 (min)              ← 법정상한, 조례 (강화 방향)
 *
 * 사고가 났던 코드는 cap 하나뿐이었다:
 *
 *   const 건폐율 = Math.min(법정상한, 조례)   // 20, 20 → 20
 *
 * 특별법 특례는 완화 방향(60%)이라 min 에 넣으면 언제나 진다.
 * override 를 cap 으로 처리하면 특례는 구조적으로 영원히 잡히지 않는다.
 *
 * 이 파일은 순수 함수만 담는다. 룰은 인자로 받는다 (브라우저 번들 그대로 가능).
 */

