const round2 = (n) => Math.round(n * 100) / 100;

/* ------------------------------------------------------------------ *
 * 1. gate — 트랙을 연다/닫는다
 * ------------------------------------------------------------------ */

/** 룰의 적용조건에 적힌 값이 대지의 구역·지구 목록에 전부 들어있는가 */
function 조건일치(적용조건 = {}, 구역 = []) {
  return Object.values(적용조건).every((v) => 구역.includes(v));
}

/**
 * 구역을 보고 어느 트랙으로 갈지 정한다.
 *
 * 특별법 구역이 감지됐는데 매칭되는 룰이 없으면 rule 은 null 이다.
 * 그때 조용히 국토계획법으로 되돌아가면 안 된다 — 그게 20% 사고였다.
 */
export function gate(구역 = [], rules = []) {
  const 감지 = 구역.filter((z) => 특별법구역.includes(z));

  if (감지.length === 0) {
    return { track: '국토계획법', 감지: [], rule: null };
  }

  const rule = rules.find((r) => 조건일치(r.적용조건, 구역)) ?? null;
  return { track: '특별법', 감지, rule };
}

/* ------------------------------------------------------------------ *
 * 2. override — 값을 갈아끼운다
 * ------------------------------------------------------------------ */

/** 자격 표기는 "5년이상거주|지정당시거주자" 처럼 파이프로 여러 개, "*" 는 전체 */
function 자격일치(룰자격, 입력자격) {
  if (룰자격 === '*') return true;
  if (!입력자격) return false;
  return String(룰자격).split('|').includes(입력자격);
}

/**
 * 용도가 맞고 자격도 충족하는 트랙을 고른다.
 *
 * "그외" 는 폴백이므로 해당 용도의 트랙이 하나도 없을 때만 쓴다.
 * 섞어서 경쟁시키면 캡이 없는 폴백(건폐율 20%)이 특례(60%)를 이겨버린다.
 */
function 후보트랙(rule, 용도, 자격) {
  const 전체 = rule.트랙 ?? [];
  const 정확 = 전체.filter((t) => t.용도 === 용도 && 자격일치(t.자격, 자격));
  if (정확.length > 0) return 정확;
  return 전체.filter((t) => t.용도 === '그외' && 자격일치(t.자격, 자격));
}

/**
 * 목적이 "최대 면적"이므로, 자격을 충족하는 트랙 중 실제로 가장 크게
 * 지을 수 있는 것을 고른다. 준법 검사기라면 여기서 min 을 쓰겠지만 이 도구는 반대다.
 */
function 최대트랙(후보, 대지면적) {
  const 규모 = (t) => {
    const a = 면적산정({ 대지면적, 건폐율: t.건폐율, 용적률: t.용적률, 연면적캡: t.연면적캡 });
    return a.최대연면적 ?? a.최대건축면적 ?? 0;
  };
  return 후보.reduce((best, t) => (best === null || 규모(t) > 규모(best) ? t : best), null);
}

/* ------------------------------------------------------------------ *
 * 3. cap — 상한을 씌운다
 * ------------------------------------------------------------------ */

/**
 * 조례는 법령 범위 안에서 "더 엄하게만" 할 수 있으므로 min 이다.
 *
 * 단, 특별법 특례에는 조례를 씌우지 않는다.
 * 국토계획법 시행령 §84④1호가 집단취락지구를 GB법령에 통째로 넘겼고,
 * 특별법 열에는 조례 칸 자체가 없다.
 */
function cap(값, 상한) {
  if (값 == null) return 상한;
  if (상한 == null) return 값;
  return Math.min(값, 상한);
}

/* ------------------------------------------------------------------ *
 * 면적 산정
 * ------------------------------------------------------------------ */

function 면적산정({ 대지면적, 건폐율, 용적률, 연면적캡 }) {
  if (!대지면적 || 건폐율 == null) return {};

  const 최대건축면적 = round2((대지면적 * 건폐율) / 100);
  const 용적률연면적 = 용적률 == null ? null : round2((대지면적 * 용적률) / 100);

  let 최대연면적 = 용적률연면적;
  let 지배제약 = 용적률연면적 == null ? null : '용적률';

  if (연면적캡 != null && (최대연면적 == null || 연면적캡 < 최대연면적)) {
    최대연면적 = 연면적캡;
    지배제약 = '연면적 캡';
  }

  // 연면적을 못 구한 트랙은 그 사실을 숨기지 않는다.
  // (GB 기본 트랙처럼 룰에 용적률·캡이 아직 없는 경우)
  const 미상 = 최대연면적 == null ? ['연면적 기준 미확보 — 건축면적만 산정됨'] : [];

  return { 최대건축면적, 용적률연면적, 최대연면적, 지배제약, 미상 };
}

/** 면적을 산정하고, 못 구한 항목은 경고로 옮겨 담는다 */
function 적용면적(입력, 경고) {
  const { 미상 = [], ...값 } = 면적산정(입력);
  경고.push(...미상);
  return 값;
}

/* ------------------------------------------------------------------ *
 * 진입점
 * ------------------------------------------------------------------ */

/**
 * @param {object} 대지    { 대지면적, 용도지역, 구역:[], 용도, 자격 }
 * @param {object} 옵션    { rules:[], 용도지역표 }
 */
export function resolve(대지 = {}, { rules = [], 용도지역표 = 용도지역시드 } = {}) {
  const { 대지면적, 용도지역, 구역 = [], 용도 = null, 자격 = null, 시도 = null } = 대지;
  const 근거 = [];
  const 경고 = [];

  const g = gate(구역, rules);

  /* --- 특별법 트랙 --- */
  if (g.track === '특별법') {
    근거.push(`구역 감지: ${g.감지.join(', ')} → 국토계획법 용도지역 기준 미적용`);

    // 룰이 없으면 숫자를 내지 않는다. 이 분기가 사고를 막는 지점이다.
    if (!g.rule) {
      const 봐야할것 = g.감지.map((z) => `${z} → ${차단구역[z]}`);
      return {
        status: STATUS.NEEDS_REVIEW,
        track: g.track,
        감지: g.감지,
        메시지: '특별법 적용 구역 — 매칭되는 룰이 없어 자동 산정할 수 없습니다',
        확인대상: 봐야할것,
        근거,
        경고: ['용도지역 기준으로 대신 계산하지 마세요. 별표 확보 후 룰을 추가해야 합니다.'],
      };
    }

    const rule = g.rule;
    근거.push(`${rule.법령} ${(rule.근거 ?? []).join(' · ')}`);
    if (rule.검수상태 !== '검수완료') {
      경고.push(`룰 "${rule.id}" 미검수 — 조문 원문 대조 전입니다`);
    }

    // 용도를 모르면 값이 갈린다. 하나로 확정하지 않고 분기표를 준다.
    if (!용도) {
      const 분기 = (rule.트랙 ?? []).map((t) => {
        const { 미상, ...면적 } = 면적산정({
          대지면적, 건폐율: t.건폐율, 용적률: t.용적률, 연면적캡: t.연면적캡,
        });
        return { 용도: t.용도, 자격: t.자격, 건폐율: t.건폐율, ...면적, 비고: t.비고 };
      });
      return {
        status: STATUS.INPUT_REQUIRED,
        track: g.track,
        감지: g.감지,
        메시지: '용도에 따라 건폐율이 갈립니다. 용도를 지정해야 확정됩니다',
        분기,
        근거,
        경고,
      };
    }

    const 후보 = 후보트랙(rule, 용도, 자격);
    if (후보.length === 0) {
      return {
        status: STATUS.NEEDS_REVIEW,
        track: g.track,
        감지: g.감지,
        메시지: `용도 "${용도}" / 자격 "${자격 ?? '미입력'}" 에 해당하는 트랙이 없습니다`,
        근거,
        경고,
      };
    }

    const t = 최대트랙(후보, 대지면적);
    if (t.용도 === '그외') {
      근거.push('취락지구 밖 개발제한구역 기준 준용');
    }
    if (t.비고) 경고.push(t.비고);

    return {
      status: STATUS.OK,
      track: g.track,
      감지: g.감지,
      적용트랙: { 용도: t.용도, 자격: t.자격 },
      건폐율: t.건폐율,
      용적률: t.용적률 ?? null,
      층수: t.층수 ?? null,
      연면적캡: t.연면적캡 ?? null,
      ...적용면적({ 대지면적, 건폐율: t.건폐율, 용적률: t.용적률, 연면적캡: t.연면적캡 }, 경고),
      연면적산입: rule.연면적산입 ?? null,
      근거,
      경고,
    };
  }

  /* --- 국토계획법 트랙 --- */

  // 조례는 지자체마다 다르다. 서울 표를 용인 필지에 쓰면 조용히 틀린다.
  const 표지역 = 용도지역표?.적용지역;
  if (표지역 && 시도 !== 표지역) {
    return {
      status: STATUS.NEEDS_REVIEW,
      track: g.track,
      메시지: `용도지역 기준표는 ${표지역} 조례입니다 (대지 소재: ${시도 ?? '미입력'})`,
      근거,
      경고: [`${시도 ?? '해당 지자체'} 도시계획조례를 확보해 기준표를 추가해야 합니다.`],
    };
  }

  const z = 용도지역표?.값?.[용도지역];
  if (!z) {
    return {
      status: STATUS.NEEDS_REVIEW,
      track: g.track,
      메시지: `용도지역 "${용도지역 ?? '미입력'}" 기준이 없습니다`,
      근거,
      경고,
    };
  }

  if (용도지역표.검수상태 !== '검수완료') {
    경고.push(`용도지역 기준표 ${용도지역표.검수상태} — ${용도지역표.출처}`);
  }

  const 건폐율 = cap(z.조례?.건폐율, z.법정상한?.건폐율);
  const 용적률 = cap(z.조례?.용적률, z.법정상한?.용적률);
  근거.push(`${용도지역} · 법정상한 ${z.법정상한.건폐율}% → 조례 ${z.조례.건폐율}% (cap)`);

  return {
    status: STATUS.OK,
    track: g.track,
    감지: [],
    건폐율,
    용적률,
    ...적용면적({ 대지면적, 건폐율, 용적률 }, 경고),
    근거,
    경고,
  };
}
